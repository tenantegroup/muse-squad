#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(mktemp -d "${TMPDIR:-/tmp}/muse-squad-test.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT

# These tests verify installer behavior, not Muse discovery. Dedicated cases
# below opt back into preflight where needed.
export MUSE_SQUAD_SKIP_MUSE_CHECK=1

fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }
latest_backup() { ls -1dt "$1".backup.* 2>/dev/null | head -n 1 || true; }
permissions() { stat -f %Lp "$1" 2>/dev/null || stat -c %a "$1" 2>/dev/null || true; }

PAYLOAD_PATHS=(
  "skills/squad-team/SKILL.md"
  "skills/squad-doctor/SKILL.md"
  "skills/squad-plan/SKILL.md"
  "skills/squad-execute/SKILL.md"
  "mcp/bridge.js"
  "mcp/config.js"
  "mcp/doctor.js"
  "mcp/register-settings.js"
  "mcp/sync-team.js"
)

GENERIC_AGENTS=(worker plan-reviewer general-purpose)
MEMBERS=(team-lead frontend backend tester secretary)

verify_settings() {
  SETTINGS="$1" EXPECT_CONFIG="$2" node -e '
    const fs = require("fs");
    const s = JSON.parse(fs.readFileSync(process.env.SETTINGS, "utf8"));
    const servers = s.mcpServers || {};
    const c = servers["muse-squad"];
    if (!c) throw new Error("missing muse-squad MCP registration");
    if (c.transport !== "stdio") throw new Error("bad transport");
    if (c.command !== "node") throw new Error("bad command");
    if (!Array.isArray(c.args) || !c.args[0].replace(/\\/g, "/").endsWith("mcp/bridge.js")) {
      throw new Error("bad bridge args");
    }
    if (!c.env || c.env.MUSE_SQUAD_CONFIG_FILE !== process.env.EXPECT_CONFIG) {
      throw new Error("bad MUSE_SQUAD_CONFIG_FILE");
    }
    for (const key of ["MODELS_CONFIG_FILE", "OPENAI_BASE_URL", "OPENAI_API_KEY", "MODEL_NAME", "DEFAULT_ENDPOINT"]) {
      if (key in (c.env || {})) throw new Error(`unexpected legacy env: ${key}`);
    }
    if (c.mode !== "optional") throw new Error("bad mode");
    if (Object.prototype.hasOwnProperty.call(servers, "custom-coder")) {
      throw new Error("legacy custom-coder registration still present");
    }
    if (s.mcp_servers && Object.prototype.hasOwnProperty.call(s.mcp_servers, "custom-coder")) {
      throw new Error("legacy mcp_servers.custom-coder still present");
    }
  '
}

verify_config() {
  node "$ROOT/payload/mcp/config.js" --file "$1" --json > /dev/null
}

verify_roster() {
  local dir="$1"
  grep -qF '| @name | Primary | Fallback | Focus |' "$dir/squad/team.md" || \
    fail "$dir/squad/team.md has no member table"
  grep -qF '| @team-lead |' "$dir/squad/team.md" || fail "$dir/squad/team.md is missing @team-lead"
  for name in "${MEMBERS[@]}"; do
    [[ -f "$dir/agents/$name.md" ]] || fail "$dir/agents/$name.md is missing"
    grep -qF 'Generated by muse-squad sync-team.js' "$dir/agents/$name.md" || \
      fail "$dir/agents/$name.md is missing the generated marker"
    grep -qF "muse-squad:generate_code" "$dir/agents/$name.md" || \
      fail "$dir/agents/$name.md does not document member-scoped generation"
    grep -qF "member=\"$name\"" "$dir/agents/$name.md" || \
      fail "$dir/agents/$name.md is not scoped to @$name"
  done
  grep -qF '[team-lead | Muse-Spark] <action>' "$dir/agents/team-lead.md" || \
    fail "@team-lead wrapper is missing the new TUI label"
}

echo "== bash installer: fresh install =="
BASE="$TMP/bash-config"
install_output="$(MUSE_CONFIG_DIR="$BASE" bash "$ROOT/install")"
printf '%s\n' "$install_output"
[[ -z "$(latest_backup "$BASE")" ]] || fail "fresh install created a backup"
grep -q 'created.*muse-squad.toml' <<<"$install_output" || \
  fail "install did not seed muse-squad.toml"
grep -q 'sync-team: 5 members' <<<"$install_output" || \
  fail "install did not run sync-team.js"

echo "== bash installer: verify payload =="
for rel in "${PAYLOAD_PATHS[@]}"; do
  diff -q --strip-trailing-cr "$ROOT/payload/$rel" "$BASE/$rel"
  echo "  ok  $rel"
done
for rel in endpoints.json squad-team.json; do
  [[ ! -e "$BASE/$rel" ]] || fail "legacy config file was installed: $rel"
done
for name in "${GENERIC_AGENTS[@]}"; do
  [[ ! -e "$BASE/agents/$name.md" ]] || fail "generic agent was installed: $name.md"
done
[[ ! -e "$ROOT/payload/agents/worker.md" ]] || fail "worker.md still exists in payload"
[[ "$(permissions "$BASE/muse-squad.toml")" == "600" ]] || \
  fail "seeded config is not chmod 600"

echo "== bash installer: verify single config =="
diff -q --strip-trailing-cr "$ROOT/payload/muse-squad.default.toml" "$BASE/muse-squad.toml"
verify_config "$BASE/muse-squad.toml"
verify_settings "$BASE/settings.json" "$BASE/muse-squad.toml"
verify_roster "$BASE"

echo "== bash installer: verify delegation policy =="
{
  printf '%s\n' '<!-- muse-squad:begin -->'
  cat "$ROOT/payload/AGENTS.md"
  printf '%s\n' '<!-- muse-squad:end -->'
} > "$TMP/expected-agents.md"
diff -q --strip-trailing-cr "$TMP/expected-agents.md" "$BASE/AGENTS.md"
for phrase in \
  'The MCP server is `muse-squad`' \
  'All implementation, exploration, and review work goes to a named squad member' \
  'Label every spawned subagent exactly as `[<name> | <provider-name>] <action>`'; do
  grep -qF "$phrase" "$ROOT/payload/AGENTS.md" || fail "missing policy phrase: $phrase"
done

echo "== bash installer: idempotent rerun and backup =="
rerun_output="$(MUSE_CONFIG_DIR="$BASE" bash "$ROOT/install")"
printf '%s\n' "$rerun_output"
grep -q 'unchanged.*muse-squad.toml' <<<"$rerun_output" || \
  fail "rerun did not report the config unchanged"
grep -q 'unchanged.*agents/team-lead.md' <<<"$rerun_output" || \
  fail "rerun did not report generated wrappers unchanged"
backup="$(latest_backup "$BASE")"
[[ -n "$backup" ]] || fail "non-interactive rerun did not create a backup"
grep -qF "  restore      $backup" <<<"$rerun_output" || \
  fail "backup output did not print only the restore path"

echo "== bash installer: backup flags =="
NO_BACKUP_DIR="$TMP/no-backup"
MUSE_CONFIG_DIR="$NO_BACKUP_DIR" bash "$ROOT/install" --no-backup >/dev/null
MUSE_CONFIG_DIR="$NO_BACKUP_DIR" MUSE_SQUAD_NO_BACKUP=1 bash "$ROOT/install" >/dev/null
[[ -z "$(latest_backup "$NO_BACKUP_DIR")" ]] || \
  fail "MUSE_SQUAD_NO_BACKUP=1 was not respected"
FORCED_BACKUP_OUTPUT="$(MUSE_CONFIG_DIR="$NO_BACKUP_DIR" MUSE_SQUAD_NO_BACKUP=1 bash "$ROOT/install" --backup)"
grep -q 'backed up' <<<"$FORCED_BACKUP_OUTPUT" || \
  fail "--backup did not override MUSE_SQUAD_NO_BACKUP=1"

echo "== bash installer: --dir with MUSE.md policy target =="
EXPLICIT_DIR="$TMP/explicit-config"
mkdir -p "$EXPLICIT_DIR"
printf 'my own notes\n' > "$EXPLICIT_DIR/MUSE.md"
EXPLICIT_OUTPUT="$(bash "$ROOT/install" --dir "$EXPLICIT_DIR" --no-backup)"
printf '%s\n' "$EXPLICIT_OUTPUT"
[[ ! -e "$EXPLICIT_DIR/AGENTS.md" ]] || \
  fail "installer created AGENTS.md when MUSE.md already existed"
grep -qF 'my own notes' "$EXPLICIT_DIR/MUSE.md" || \
  fail "installer removed user content from MUSE.md"
grep -qF '<!-- muse-squad:begin -->' "$EXPLICIT_DIR/MUSE.md" || \
  fail "managed policy was not appended to MUSE.md"
verify_config "$EXPLICIT_DIR/muse-squad.toml"
verify_settings "$EXPLICIT_DIR/settings.json" "$EXPLICIT_DIR/muse-squad.toml"

echo "== bash installer: interactive team wizard =="
INTERACTIVE_DIR="$TMP/interactive-config"
MUSE_CONFIG_DIR="$INTERACTIVE_DIR" bash "$ROOT/install" --no-backup >/dev/null
WIZARD_INPUT=(y oracle Muse-Ember Home-Ornith "Custom charter for oracle.")
for _ in 1 2 3 4; do
  WIZARD_INPUT+=("" "" "" "")
done
WIZARD_INPUT+=(y scout Muse-Spark DeepSeek-Flash "Custom charter for scout." n)
interactive_status=0
interactive_output="$(
  MUSE_CONFIG_DIR="$INTERACTIVE_DIR" MUSE_SQUAD_FORCE_INTERACTIVE=1 \
    bash "$ROOT/install" --reconfigure-team --no-backup < <(printf '%s\n' "${WIZARD_INPUT[@]}") 2>&1
)" || interactive_status=$?
printf '%s\n' "$interactive_output"
[[ "$interactive_status" -eq 0 ]] || \
  fail "interactive installer exited with status $interactive_status"
grep -qF 'Customize Squad team members & models now?' <<<"$interactive_output" || \
  fail "interactive install did not ask the wizard question"
grep -qF 'Member 1 name [team-lead]:' <<<"$interactive_output" || \
  fail "interactive install did not prompt for member names"
grep -qF 'Primary provider for oracle' <<<"$interactive_output" || \
  fail "interactive install did not prompt for providers"
grep -qF 'Charter for oracle' <<<"$interactive_output" || \
  fail "interactive install did not prompt for charters"
grep -qF '1: Home-Ornith, 2: DeepSeek-Flash, 3: Muse-Spark, 4: Muse-Ember, 5: Muse-Wonder' <<<"$interactive_output" || \
  fail "interactive install did not build the provider menu from the TOML config"

INTERACTIVE_CONFIG="$INTERACTIVE_DIR/muse-squad.toml" node -e '
  const config = require(process.env.INTERACTIVE_CONFIG.replace(/muse-squad\.toml$/, "mcp/config.js"))
    .loadConfig({ config_file: process.env.INTERACTIVE_CONFIG });
  const actual = Object.values(config.squad.members).map((m) => [m.name, m.primary, m.fallback]);
  const expected = [
    ["oracle", "Muse-Ember", ["Home-Ornith"]],
    ["frontend", "Home-Ornith", ["Muse-Ember"]],
    ["backend", "Home-Ornith", ["DeepSeek-Flash"]],
    ["tester", "Home-Ornith", ["Muse-Ember"]],
    ["secretary", "Muse-Ember", ["Home-Ornith"]],
    ["scout", "Muse-Spark", ["DeepSeek-Flash"]]
  ];
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error(`bad interactive roster: ${JSON.stringify(actual)}`);
  }
  if (config.squad.members.oracle.charter.trim() !== "Custom charter for oracle.") {
    throw new Error("custom oracle charter was not written");
  }
  if (config.squad.members.scout.charter.trim() !== "Custom charter for scout.") {
    throw new Error("custom scout charter was not written");
  }
'
[[ ! -e "$INTERACTIVE_DIR/agents/team-lead.md" ]] || \
  fail "stale generated wrapper was not removed after renaming @team-lead"
grep -qF '| @oracle |' "$INTERACTIVE_DIR/squad/team.md" || \
  fail "team.md is missing the renamed @oracle member"
grep -qF '| @scout |' "$INTERACTIVE_DIR/squad/team.md" || \
  fail "team.md is missing the extra @scout member"
grep -qF '[oracle | Muse-Ember] <action>' "$INTERACTIVE_DIR/agents/oracle.md" || \
  fail "@oracle wrapper has the wrong TUI label"
for name in oracle frontend backend tester secretary scout; do
  [[ -f "$INTERACTIVE_DIR/agents/$name.md" ]] || fail "missing custom agent @$name"
done

echo "== bash installer: wizard retries invalid input =="
RETRY_DIR="$TMP/retry-config"
MUSE_CONFIG_DIR="$RETRY_DIR" bash "$ROOT/install" --no-backup >/dev/null
RETRY_INPUT=(y 3 team-lead 1 1 3 "Retry charter.")
for _ in 1 2 3 4; do
  RETRY_INPUT+=("" "" "" "")
done
RETRY_INPUT+=(n)
retry_status=0
retry_output="$(
  MUSE_CONFIG_DIR="$RETRY_DIR" MUSE_SQUAD_FORCE_INTERACTIVE=1 \
    bash "$ROOT/install" --reconfigure-team --no-backup < <(printf '%s\n' "${RETRY_INPUT[@]}") 2>&1
)" || retry_status=$?
printf '%s\n' "$retry_output"
[[ "$retry_status" -eq 0 ]] || \
  fail "wizard retry installer exited with status $retry_status"
grep -qF 'member name must include at least one letter' <<<"$retry_output" || \
  fail "wizard did not reject a numeric member name"
grep -qF 'fallback must not repeat the primary provider: Home-Ornith' <<<"$retry_output" || \
  fail "wizard did not reject a repeated fallback provider"
grep -qF 'Charter for team-lead' <<<"$retry_output" || \
  fail "wizard did not return to the corrected member"

RETRY_CONFIG="$RETRY_DIR/muse-squad.toml" node -e '
  const config = require(process.env.RETRY_CONFIG.replace(/muse-squad\.toml$/, "mcp/config.js"))
    .loadConfig({ config_file: process.env.RETRY_CONFIG });
  const member = config.squad.members["team-lead"];
  if (!member) throw new Error("corrected member was not written");
  if (member.primary !== "Home-Ornith") throw new Error("corrected primary was not applied");
  if (JSON.stringify(member.fallback) !== JSON.stringify(["Muse-Spark"])) {
    throw new Error(`corrected fallback was not applied: ${JSON.stringify(member.fallback)}`);
  }
  if (member.charter.trim() !== "Retry charter.") throw new Error("corrected charter was not applied");
  if (config.squad.members["3"]) throw new Error("numeric member name was written");
'
[[ ! -e "$RETRY_DIR/agents/3.md" ]] || \
  fail "wizard generated a wrapper for the rejected numeric member"

echo "== bash installer: wizard repairs an invalid squad config =="
BROKEN_DIR="$TMP/broken-config"
MUSE_CONFIG_DIR="$BROKEN_DIR" bash "$ROOT/install" --no-backup >/dev/null
perl -0pi -e 's/(\[squad\.team-lead\].*?fallback = \[)"DeepSeek-Flash"\]/${1}"Muse-Spark"]/s' \
  "$BROKEN_DIR/muse-squad.toml"
if node "$BROKEN_DIR/mcp/config.js" --file "$BROKEN_DIR/muse-squad.toml" \
    --list-providers >/dev/null 2>&1; then
  fail "test setup did not produce an invalid config"
fi
BROKEN_INPUT=(y)
for _ in 1 2 3 4 5; do
  BROKEN_INPUT+=("" "" "" "")
done
BROKEN_INPUT+=(n)
broken_status=0
broken_output="$(
  MUSE_CONFIG_DIR="$BROKEN_DIR" MUSE_SQUAD_FORCE_INTERACTIVE=1 \
    bash "$ROOT/install" --reconfigure-team --no-backup < <(printf '%s\n' "${BROKEN_INPUT[@]}") 2>&1
)" || broken_status=$?
printf '%s\n' "$broken_output"
[[ "$broken_status" -eq 0 ]] || \
  fail "wizard could not repair an invalid config (status $broken_status)"
node "$BROKEN_DIR/mcp/config.js" --file "$BROKEN_DIR/muse-squad.toml" \
  --list-providers >/dev/null 2>&1 || fail "wizard left the config invalid"

echo "== bash installer: prompts with piped stdin =="
PIPED_DIR="$TMP/piped-config"
TTY_FILE="$TMP/piped-tty"
PIPED_ANSWERS=(y piped-member Muse-Ember Home-Ornith "Piped charter.")
for _ in 1 2 3 4; do
  PIPED_ANSWERS+=("" "" "" "")
done
PIPED_ANSWERS+=(n)
printf '%s\n' "${PIPED_ANSWERS[@]}" > "$TTY_FILE"
piped_status=0
piped_output="$(
  MUSE_CONFIG_DIR="$PIPED_DIR" MUSE_SQUAD_TTY="$TTY_FILE" \
    bash -s < "$ROOT/install" 2>&1
)" || piped_status=$?
printf '%s\n' "$piped_output"
[[ "$piped_status" -eq 0 ]] || \
  fail "piped installer exited with status $piped_status"
grep -qF 'Customize Squad team members & models now?' <<<"$piped_output" || \
  fail "piped install did not prompt through MUSE_SQUAD_TTY"
grep -qF 'Member 1 name [team-lead]:' <<<"$piped_output" || \
  fail "piped install did not prompt for member names"
grep -qF 'Charter for piped-member' <<<"$piped_output" || \
  fail "piped install did not prompt for the custom charter"

PIPED_CONFIG="$PIPED_DIR/muse-squad.toml" node -e '
  const config = require(process.env.PIPED_CONFIG.replace(/muse-squad\.toml$/, "mcp/config.js"))
    .loadConfig({ config_file: process.env.PIPED_CONFIG });
  const member = config.squad.members["piped-member"];
  if (!member) throw new Error("piped-member was not written to the config");
  if (member.primary !== "Muse-Ember") throw new Error("piped primary was not applied");
  if (member.fallback[0] !== "Home-Ornith") throw new Error("piped fallback was not applied");
  if (member.charter.trim() !== "Piped charter.") throw new Error("piped charter was not applied");
'
grep -qF '[piped-member | Muse-Ember] <action>' "$PIPED_DIR/agents/piped-member.md" || \
  fail "piped-member wrapper has the wrong TUI label"

RERUN_TTY="$TMP/piped-rerun-tty"
printf 'n\nn\n' > "$RERUN_TTY"
piped_rerun_output="$(
  MUSE_CONFIG_DIR="$PIPED_DIR" MUSE_SQUAD_TTY="$RERUN_TTY" \
    bash -s -- --reconfigure-team < "$ROOT/install" 2>&1
)"
printf '%s\n' "$piped_rerun_output"
grep -qF 'Back up current Muse config before continuing? [Y/n]:' <<<"$piped_rerun_output" || \
  fail "piped rerun did not prompt for backup through MUSE_SQUAD_TTY"
grep -qF 'skipped      backup (user chose no)' <<<"$piped_rerun_output" || \
  fail "piped backup answer was not applied"
[[ -z "$(latest_backup "$PIPED_DIR")" ]] || \
  fail "piped rerun created a backup after choosing no"

echo "== bash installer: uninstall =="
UNINSTALL_DIR="$TMP/uninstall-config"
mkdir -p "$UNINSTALL_DIR/agents"
printf 'my own notes\n' > "$UNINSTALL_DIR/AGENTS.md"
bash "$ROOT/install" --dir "$UNINSTALL_DIR" --no-backup >/dev/null
node -e '
  const fs = require("fs");
  const file = process.argv[1];
  const s = JSON.parse(fs.readFileSync(file, "utf8"));
  s.mcpServers["custom-coder"] = { transport: "stdio", command: "node", args: [] };
  fs.writeFileSync(file, JSON.stringify(s, null, 2) + "\n");
' "$UNINSTALL_DIR/settings.json"
printf 'legacy\n' > "$UNINSTALL_DIR/agents/worker.md"
printf 'user file\n' > "$UNINSTALL_DIR/agents/keep.md"
uninstall_output="$(bash "$ROOT/install" --dir "$UNINSTALL_DIR" --uninstall)"
printf '%s\n' "$uninstall_output"
uninstall_backup="$(latest_backup "$UNINSTALL_DIR")"
[[ -n "$uninstall_backup" ]] || fail "uninstall did not create a backup"
[[ -f "$uninstall_backup/muse-squad.toml" ]] || \
  fail "uninstall backup lost the TOML config"
node -e '
  const fs = require("fs");
  const s = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
  if (s.mcpServers && s.mcpServers["muse-squad"]) throw new Error("muse-squad still registered");
  if (s.mcpServers && s.mcpServers["custom-coder"]) throw new Error("custom-coder still registered");
' "$UNINSTALL_DIR/settings.json"
grep -qF 'my own notes' "$UNINSTALL_DIR/AGENTS.md" || \
  fail "uninstall removed user content from AGENTS.md"
if grep -qF '<!-- muse-squad:begin -->' "$UNINSTALL_DIR/AGENTS.md"; then
  fail "uninstall left the managed policy block behind"
fi
[[ -f "$UNINSTALL_DIR/muse-squad.toml" ]] || fail "uninstall removed muse-squad.toml"
grep -q 'kept.*muse-squad.toml' <<<"$uninstall_output" || \
  fail "uninstall did not report that the config was kept"
for name in "${MEMBERS[@]}"; do
  [[ ! -e "$UNINSTALL_DIR/agents/$name.md" ]] || \
    fail "uninstall left generated wrapper @$name behind"
done
[[ ! -e "$UNINSTALL_DIR/agents/worker.md" ]] || \
  fail "uninstall left the legacy generic agent behind"
[[ ! -e "$UNINSTALL_DIR/squad/team.md" ]] || fail "uninstall left squad/team.md behind"
[[ -f "$UNINSTALL_DIR/agents/keep.md" ]] || \
  fail "uninstall removed an unmarked user agent"

echo "== installer help =="
help_output="$(bash "$ROOT/install" --help)"
for option in --dir --update --uninstall --no-mcp --backup --no-backup \
  --reconfigure-team --defaults --skip-muse-check --help; do
  grep -qF -- "$option" <<<"$help_output" || fail "help is missing $option"
done

echo "== PowerShell installer structure =="
# node -e has no script path in argv; the placeholder keeps argv[2]/[3] correct.
for phrase in \
  "function Install-Config" \
  "Install-Config (Get-Config-Defaults)" \
  "function Test-Console-Input" \
  "function Read-Interactive" \
  "function Test-Member-Name" \
  "function Test-Fallback-List" \
  "fallback must not repeat the primary provider" \
  "team config failed validation; no changes were written" \
  "MUSE_SQUAD_TTY" \
  "Get-Dest 'muse-squad.toml'" \
  "--uninstall         Remove managed files and unregister muse-squad" \
  '& node -e $nodeScript - $dest $membersFile'; do
  grep -qF -- "$phrase" "$ROOT/install.ps1" || fail "install.ps1 is missing: $phrase"
done
for phrase in endpoints.json squad-team.json; do
  if grep -qF "$phrase" "$ROOT/install.ps1"; then
    fail "install.ps1 still references $phrase"
  fi
done

echo "== payload documentation =="
for file in "$ROOT/payload/AGENTS.md" "$ROOT/README.md" "$ROOT/payload/skills"/*/SKILL.md; do
  for phrase in endpoints.json squad-team.json custom-coder fallback_endpoint muse_models; do
    if grep -qF "$phrase" "$file"; then
      fail "$file still references $phrase"
    fi
  done
done

echo "ALL INSTALL TESTS PASSED"
